// Exports the agent profile for Qutai Credits (src/credits/profile.ts) and prints its SHA-256, the profile id.
//
//   npm run profile:export   writes agent-profile/profile.json and src/credits/agentProfileId.ts
//   npm run profile:check    fails (exit 1) when either is out of date with the app's prompt and tools
//
// The id is the SHA-256 of the file's exact bytes, as the server's backend/scripts/agent-profile-sql.mjs computes
// it. Registering the profile on a server is a separate step (README.md › Qutai Credits › Agent profile).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { agentProfileJson } from '../../src/credits/profile.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const PROFILE_FILE = join(root, 'agent-profile', 'profile.json');
export const ID_FILE = join(root, 'src', 'credits', 'agentProfileId.ts');

export function profileId(json: string): string {
  return createHash('sha256').update(json, 'utf8').digest('hex');
}

export function idModule(id: string): string {
  return (
    '// Generated by `npm run profile:export` (scripts/agent-profile/export.ts) from src/credits/profile.ts: do not edit.\n' +
    '// The SHA-256 of agent-profile/profile.json, sent as `profile` with every Qutai Credits request.\n' +
    `export const AGENT_PROFILE_ID = '${id}';\n`
  );
}

/** What is out of date: [] when both files match the source. */
export function staleFiles(): string[] {
  const json = agentProfileJson();
  const read = (file: string) => {
    try {
      return readFileSync(file, 'utf8');
    } catch {
      return null;
    }
  };
  const stale: string[] = [];
  if (read(PROFILE_FILE) !== json) stale.push('agent-profile/profile.json');
  if (read(ID_FILE) !== idModule(profileId(json))) stale.push('src/credits/agentProfileId.ts');
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const json = agentProfileJson();
  const id = profileId(json);
  if (process.argv.includes('--check')) {
    const stale = staleFiles();
    if (stale.length) {
      console.error(
        `The agent profile is out of date (${stale.join(', ')}): the system prompt or the tools changed.\n` +
          'Run `npm run profile:export`, commit both files, and register the new profile on the servers before the release.',
      );
      process.exit(1);
    }
    console.log(id);
  } else {
    writeFileSync(PROFILE_FILE, json);
    writeFileSync(ID_FILE, idModule(id));
    console.log(id);
  }
}
